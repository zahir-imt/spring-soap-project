const assert=require('node:assert/strict');
const tools=require('../../src/main/resources/static/catalog.js');
const products=[{sku:'B',name:'Beta',category:'Office',price:20,quantity:0,reorderLevel:5},{sku:'A',name:'Alpha',category:'Office',price:10,quantity:5,reorderLevel:5},{sku:'C',name:'Cable',category:'Tech',price:5,quantity:9,reorderLevel:2}];
assert.deepEqual(tools.select(products,{stock:'out'}).map(p=>p.sku),['B']);
assert.deepEqual(tools.select(products,{stock:'low'}).map(p=>p.sku),['A']);
assert.deepEqual(tools.select(products,{stock:'healthy'}).map(p=>p.sku),['C']);
assert.deepEqual(tools.select(products,{query:' OFFICE ',stock:'low'}).map(p=>p.sku),['A']);
assert.equal(tools.select(products,{category:'Tech',stock:'low'}).length,0);
assert.deepEqual(tools.select(products,{sort:'quantity'}).map(p=>p.sku),['B','A','C']);
assert.deepEqual(tools.select(products,{sort:'value'}).map(p=>p.sku),['A','C','B']);
assert.deepEqual(products.map(p=>p.sku),['B','A','C']);
assert.deepEqual(tools.summary(products),{count:3,units:14,value:95});
const csv=tools.csv([{...products[0],name:'=HYPERLINK("https://bad.example")',category:'Office, "special"\nline'}]);
assert.ok(csv.startsWith('\uFEFF"SKU"'));
assert.ok(csv.includes('"\'=HYPERLINK(""https://bad.example"")"'));
assert.ok(csv.includes('"Office, ""special""\nline"'));
for(const value of ['+cmd','-cmd','@SUM(1)','  =cmd','\t=cmd','\r=cmd']) assert.ok(tools.csv([{...products[0],name:value}]).includes('"\''+value+'"'));
assert.equal(tools.csv([]).split('\r\n').length,2);
console.log('PASS: catalogue filtering, stock boundaries, sorting, totals, immutability, CSV quoting and spreadsheet formula protection');
