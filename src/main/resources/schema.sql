CREATE TABLE IF NOT EXISTS products (
 sku VARCHAR(32) PRIMARY KEY, name VARCHAR(100) NOT NULL, category VARCHAR(60) NOT NULL,
 price DECIMAL(12,2) NOT NULL CHECK(price >= 0), quantity INT NOT NULL CHECK(quantity >= 0),
 reorder_level INT NOT NULL CHECK(reorder_level >= 0)
);
CREATE TABLE IF NOT EXISTS customer_orders (
 id VARCHAR(36) PRIMARY KEY, customer VARCHAR(100) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('CONFIRMED','CANCELLED')),
 total DECIMAL(18,2) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS order_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id VARCHAR(36) NOT NULL REFERENCES customer_orders(id),
 sku VARCHAR(32) NOT NULL REFERENCES products(sku), name VARCHAR(100) NOT NULL,
 quantity INT NOT NULL CHECK(quantity > 0), unit_price DECIMAL(12,2) NOT NULL,
 UNIQUE(order_id, sku)
);
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku VARCHAR(32) NOT NULL REFERENCES products(sku), delta INT NOT NULL,
 balance INT NOT NULL, reason VARCHAR(150) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
